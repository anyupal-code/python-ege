from ipaddress import *

# 1. Основы: создание сети
print("=== 1. Создание сети ===")
net = ip_network('10.100.202.34/255.255.240.0', 0)
print(f'Сеть: {net}')

# 2. Свойства сети
print("\n=== 2. Свойства сети ===")
print(f'Адрес сети:      {net[0]}')
print(f'Broadcast:       {net[-1]}')
print(f'Первый хост:     {net[1]}')
print(f'Последний хост:  {net[-2]}')
print(f'Всего адресов:   {net.num_addresses}')
print(f'Устройств:       {net.num_addresses - 2}')

# 3. Перевод в двоичный вид и срезы
print("\n=== 3. Двоичный вид ===")
ip = ip_address('192.168.1.10')
ip_b = f'{ip:b}'
print(f'IP: {ip}')
print(f'Двоичный: {ip_b}')
print(f'Левые 16 бит:  {ip_b[:16]}')
print(f'Правые 16 бит: {ip_b[16:]}')

# 4. Нахождение IP-адреса срезом
print("\n=== 4. Поиск IP срезом ===")
net_24 = ip_network('192.168.0.0/24')
print(f'16-й адрес: {net_24[15]}')
print(f'Предпоследний: {net_24[-2]}')

# 5. Нахождение маски перебором
print("\n=== 5. Перебор маски (префикса) ===")
# Ищем маску для сети, где адрес сети = 192.168.1.128
for m in range(33):
    net_m = ip_network(f'192.168.1.133/{m}', 0)
    if str(net_m.network_address) == '192.168.1.128':
        print(f'Найдена маска: {net_m.netmask} (/{m})')
        break

# 6. Нахождение маски с перебором октета
print("\n=== 6. Перебор октета маски ===")
masks = [
    '00000000', '10000000', '11000000', '11100000',
    '11110000', '11111000', '11111100', '11111110', '11111111'
]

for A in masks:
    net_a = ip_network(f'192.168.0.15/255.255.255.{int(A, 2)}', 0)
    if str(net_a.network_address) == '192.168.0.0':
        print(f'Найдено A = {int(A, 2)} (маска: {net_a.netmask})')
        break