from math import ceil, log2

print("=== 1. Основная формула расчёта объёма серийного номера ===")
# Формула: sn = ceil(ceil(log2(al)) * dl / 8)
al = 150  # мощность алфавита
dl = 60   # длина серийного номера
sn = ceil(ceil(log2(al)) * dl / 8)
print(f"Мощность алфавита: {al}")
print(f"Длина номера: {dl}")
print(f"Объём одного серийного номера: {sn} байт\n")


print("=== 2. Задача A. Найти мощность алфавита ===")
# Условие: Серийный номер состоит из 143 символов.
# Для хранения 9800 серийных номеров отведено не более 780 Кбайт памяти.
# Определите максимально возможную мощность алфавита.
dl = 143  # по условию задачи
ans_al = 0
for al in range(1, 1000):
    sn = ceil(ceil(log2(al)) * dl / 8) / 1024  # объём в Килобайтах
    if 9800 * sn <= 780:
        ans_al = al  # запоминаем последнее подходящее значение
print(f"Максимально возможная мощность алфавита: {ans_al}\n")


print("=== 3. Задача B. Найти длину серийного номера ===")
# Условие: Серийный номер содержит десятичные цифры и символы из 120-символьного алфавита.
# Для хранения 12 755 226 номеров отведено не более 5 Гбайт памяти. 
# Определите максимально допустимую длину серийного номера.
al = 130  # мощность алфавита (10 цифр + 120 символов)
ans_dl = 0
for dl in range(1, 1001):
    sn = ceil(ceil(log2(al)) * dl / 8) / 1024 / 1024 / 1024  # объём в Гбайтах
    if sn * 12755226 <= 5:
        ans_dl = dl  # запоминаем последнее подходящее значение
print(f"Максимально допустимая длина серийного номера: {ans_dl}\n")


print("=== 4. Задача C. Найти объём памяти для множества номеров ===")
# Условие: Идентификатор состоит из 257 символов (цифры 17-ричной системы + 4080 символов алфавита).
# Определите объём памяти (в Мбайт) для хранения 8 388 608 идентификаторов.
dl = 257
al = 4097  # 17 (цифры) + 4080 (специальный алфавит)
sn = ceil(ceil(log2(al)) * dl / 8) / 1024 / 1024  # объём одного в Мбайтах
total_mb = sn * 8388608
print(f"Объём памяти для всех идентификаторов: {total_mb} Мбайт\n")


