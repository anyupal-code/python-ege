from string import printable

# 1. Подсчет нулей в 8-ричной системе
print("=== 1. Подсчет нулей ===")
n = 123456
c = 0
while n:
    if n % 8 == 0: c += 1
    n //= 8
print(f"Количество нулей: {c}")

# 2. Перебор переменной x (Задание 14)
print("\n=== 2. Поиск наибольшего x ===")
ans = 0
for x in range(1, 2401):
    n = 7 * 9**210 + 6 * 9**110 - x
    c = 0
    while n:
        if n % 9 == 0: c += 1
        n //= 9
    if c == 100: ans = x
print(f"Наибольшее x: {ans}") # 2394

# 3. Неизвестная цифра в 29-ричной системе
print("\n=== 3. Неизвестная цифра (29-ричная) ===")
# Найдите наименьшее x, при которой число 1x2 (в 29-ричной) делится на 3
for x in printable[:29]:
    num = int(f'1{x}2', 29)
    if num % 3 == 0:
        print(x) # 0
        break

# 4. Стандартные системы и f-строки
