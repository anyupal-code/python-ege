# main.py — готовые примеры кода к уроку «Регулярные выражения»
# Тестовые файлы *.txt лежат рядом с этим скриптом.

from re import findall, finditer


# ---------------------------------------------------------------
# 1. Максимальная длина подстроки из букв A, B, C
# ---------------------------------------------------------------
s = open("abc.txt").readline()
matches = findall(r'[ABC]+', s)
print(max(len(el) for el in matches))   # 15


# ---------------------------------------------------------------
# 2. Самая длинная цепочка одинаковых символов (через регулярку)
# ---------------------------------------------------------------
s = open("same.txt").readline()
matches = findall(r'(.)\1*', s)
print(max(len(el) for el in matches))   # 6


# ---------------------------------------------------------------
# 3. Самая длинная цепочка одинаковых символов (без регулярок)
# ---------------------------------------------------------------
s = open("same.txt").readline().strip()
mx = cur = 1
for i in range(1, len(s)):
    if s[i] == s[i - 1]:
        cur += 1
    else:
        cur = 1
    mx = max(mx, cur)
print(mx)   # 6


# ---------------------------------------------------------------
# 4. Повторяющийся блок XYZ (последний может быть неполным)
# ---------------------------------------------------------------
s = open("xyz.txt").readline()
matches = findall(r'(?:XYZ)+(?:X|XY)?', s)
print(len(max(matches, key=len)))   # 25


# ---------------------------------------------------------------
# 5. Корректное арифметическое выражение
# ---------------------------------------------------------------
s = open("arith.txt").read()
num = r"([6789][06789]*|0)"
reg = rf"{num}([-*]{num})+"
mx = max((x.group() for x in finditer(reg, s)), key=len, default="")
print(len(mx))   # 21


# ---------------------------------------------------------------
# 6. finditer — когда нужны позиции или группы
# ---------------------------------------------------------------
s = open("abc.txt").readline()
best = max(finditer(r'[ABC]+', s), key=lambda m: len(m.group()))
print(len(best.group()))         # 15
print(best.start(), best.end())  # позиции в строке