# 1. Базовый if/elif/else
print("=== 1. Базовый if ===")
x = 10
if x > 0:
    print('Положительное')
elif x == 0:
    print('Ноль')
else:
    print('Отрицательное')

# 2. Логические операторы
print("\n=== 2. Логические операторы ===")
# Изменили условие на x <= 10, чтобы пример сработал для x = 10
if (x > 0 and x <= 10) or (x == 20):
    print('x в диапазоне 1..10 или равен 20')

# 3. Тернарный оператор
print("\n=== 3. Тернарный оператор ===")
print('Чётное' if x % 2 == 0 else 'Нечётное')

# 4. all() и any()
print("\n=== 4. all() и any() ===")
numbers = [2, 4, 6, 8]
if all(el % 2 == 0 for el in numbers):
    print('Все чётные')
if any(el % 2 != 0 for el in numbers):
    print('Есть нечётное')

# 5. Есть ли буква в строке? (Проверка вхождения)
print("\n=== 5. in ===")
s = 'Hello'
if 'e' in s:
    print('Буква e есть в строке')

# 6. Сравнение цепочек
print("\n=== 6. Сравнение цепочек ===")
if 10 <= x < 20:
    print('x от 10 до 20')

# 7. Сложение булевых значений
print("\n=== 7. Сложение булевых ===")
a, b, c = 2, 4, 7
count = (a % 2 == 0) + (b % 2 == 0) + (c % 2 == 0)
print(f'Чётных: {count}')

# 8. Високосный год
print("\n=== 8. Високосный год ===")
year = 2024
if (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0):
    print(f'{year} — Високосный')
else:
    print(f'{year} — Не високосный')

# 9. Все ли числа положительные
print("\n=== 9. Все ли числа положительные ===")
nums1 = [-2, 4, 7, 9]
print('Все положительные' if all(el > 0 for el in nums1) else 'Есть отрицательные')

# 10. Есть ли чётное в списке
print("\n=== 10. Есть ли чётное ===")
nums2 = [1, 3, 5, 7, 8]
print('Есть чётное' if any(el % 2 == 0 for el in nums2) else 'Все нечётные')